/**
 * Get current daylight hours (decimal) based on the system's current date
 * Assumes your time object has: { month: 1-13, week: 1-4, year: number }
 */
export function getCurrentDaylightHours() {
  // Replace this with however your system stores the current date
  // const current = game.settings.get("hyp3e", "currentHyperboreaTime")
  //              ?? { month: 1, week: 1, year: 1 };
  const {year, month, day} = game.hyp3e.calendar.getCurrentDate();
  // Calculate the week within the the 28-day month
  const week = Math.floor((day - 1) % 7) + 1;

  // let month = Number(current.month) || 1;
  // let week  = Number(current.week)  || 1;
  // let year  = Number(current.year)  || 1;

  // Normalize to the 13-year solar cycle
  year = ((year - 1) % 13) + 1;

  const monthData = HYPERBOREA_DAYLIGHT_TABLE[month];
  if (!monthData) return 12;

  const weekData = monthData[week];
  if (!weekData || weekData.length !== 13) return 12;

  return weekData[year - 1] ?? 12;
}

/**
 * Get daylight fraction (0.0 = total darkness → 1.0 = full daylight)
 */
export function getDaylightFraction() {
  return Math.max(0, Math.min(1, getCurrentDaylightHours() / 24));
}

/**
 * Convert decimal daylight hours to "hh:mm" format
 * @param {number} decimalHours - e.g. 8.75, 17.4167, 23.9167, 0, etc.
 * @returns {string} Formatted as "hh:mm" with leading zeros (e.g. "08:45", "23:55", "00:00")
 */
export function formatDaylightAsHHMM(decimalHours) {
  // Clamp to valid range just in case
  decimalHours = Math.max(0, Math.min(24, decimalHours));

  const totalMinutes = Math.round(decimalHours * 60);   // round to nearest minute
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;

  // Format minutes with leading zeros
  return `${hours.toString()}h ${minutes.toString().padStart(2, '0')}m`;
  // return `${hours.toString()}:${minutes.toString().padStart(2, '0')}`;
  // return `${hours.toString().padStart(2, '0')}:${minutes.toString().padStart(2, '0')}`;
}